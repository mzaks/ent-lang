/// The C type that holds one element of `type` in world storage.
static StringRef getCType(Type type) {
  if (isa<EntityType>(type))
    return "ecs_entity";
  if (isa<IndexType>(type))
    return "int64_t";
  if (auto integer = dyn_cast<IntegerType>(type)) {
    switch (integer.getWidth()) {
    case 1:
      return "bool";
    case 8:
      return "int8_t";
    case 16:
      return "int16_t";
    case 32:
      return "int32_t";
    case 64:
      return "int64_t";
    }
  }
  if (type.isF32())
    return "float";
  if (type.isF64())
    return "double";
  return {};
}

/// Replace every character that cannot appear in a C identifier by '_'.
static std::string toIdentifier(StringRef name) {
  std::string result;
  for (char c : name)
    result += llvm::isAlnum(c) ? c : '_';
  if (result.empty() || llvm::isDigit(result.front()))
    result.insert(result.begin(), '_');
  return result;
}

/// Emit the C API of the world and the schedules of `module`: creation,
/// counts, typed column accessors and one entry point per schedule. The
/// header is the only place a host needs to know the layout.
static LogicalResult emitHeader(ModuleOp module, raw_ostream &os) {
  FailureOr<WorldLayout> layout = WorldLayout::compute(module);
  if (failed(layout))
    return failure();

  // Distinct names in the program may map to the same C identifier.
  llvm::StringSet<> names;
  auto claim = [&](Operation *op, const std::string &name) -> LogicalResult {
    if (!names.insert(name).second)
      return op->emitError("C name '") << name << "' is generated twice";
    return success();
  };

  os << "// Generated by ecs-translate --ecs-to-c-header. Do not edit.\n"
        "//\n"
        "// The world is one arena with a layout fixed at compile time. "
        "Create it,\n"
        "// spawn entities (ecs_<Archetype>_spawn), fill their columns, and "
        "run\n"
        "// schedules on it.\n\n"
        "#ifndef ECS_GENERATED_WORLD_H\n"
        "#define ECS_GENERATED_WORLD_H\n\n"
        "#include <stdbool.h>\n#include <stdint.h>\n#include <stdlib.h>\n"
        "#include <string.h>\n\n"
        "typedef struct ecs_world ecs_world;\n\n";
  os << llvm::formatv("#define ECS_WORLD_BYTES {0}ull\n", layout->totalBytes);
  os << llvm::formatv("#define ECS_WORLD_ALIGNMENT {0}\n\n",
                      WorldLayout::kArenaAlignment);

  os << "// Counts and resources start at zero. Columns are left "
        "uninitialised:\n// nothing reads beyond an archetype's count, and "
        "untouched pages cost\n// no memory.\n"
        "static inline ecs_world *ecs_world_create(void) {\n"
        "  void *arena = NULL;\n"
        "  if (posix_memalign(&arena, ECS_WORLD_ALIGNMENT, ECS_WORLD_BYTES))\n"
        "    return NULL;\n";
  os << llvm::formatv("  memset(arena, 0, {0});\n", layout->headerBytes);
  os << "  return (ecs_world *)arena;\n}\n\n"
        "static inline void ecs_world_destroy(ecs_world *world) { "
        "free(world); }\n";

  // Entity ids, as EntityScheme chose them. The functions below do exactly
  // what the lowered program does.
  const EntityScheme &scheme = layout->entities;
  auto uintType = [](unsigned bits) {
    return llvm::formatv("uint{0}_t", bits).str();
  };
  os << "\n// Entities: ";
  switch (scheme.kind) {
  case EntityScheme::Rows:
    os << "nothing is ever despawned or moved, so an id is\n// "
          "`archetype << ECS__ROW_BITS | row`.\n";
    break;
  case EntityScheme::Slots:
    os << "entities move but are never despawned, so an id is a\n// "
          "slot of the entity table, which records each entity's location "
          "as\n// `archetype << ECS__ROW_BITS | row`.\n";
    break;
  case EntityScheme::Generational:
    os << "an id is `generation << ECS__SLOT_BITS | slot`. Despawning\n// "
          "bumps the slot's generation, so old ids stop being alive; freed "
          "slots\n// are reused last freed first, through a list threaded "
          "through their\n// locations (`archetype << ECS__ROW_BITS | "
          "row`).\n";
    break;
  }
  os << llvm::formatv("typedef {0} ecs_entity;\n", uintType(scheme.idBits));
  os << llvm::formatv("#define ECS_NO_ENTITY UINT{0}_MAX\n", scheme.idBits);
  os << llvm::formatv("#define ECS_ENTITY_CAPACITY {0}\n",
                      layout->entityCapacity);
  os << llvm::formatv("#define ECS__ROW_BITS {0}\n", scheme.rowBits);
  os << "static inline int64_t *ecs__counts(const ecs_world *world) {\n"
        "  return (int64_t *)world;\n}\n";

  std::string allocate, alive, archetypeOf, rowOf;
  if (scheme.kind == EntityScheme::Rows) {
    allocate = "  return ((ecs_entity)archetype << ECS__ROW_BITS) | "
               "(ecs_entity)row;\n";
    os << llvm::formatv("#define ECS__ARCHETYPES {0}\n",
                        layout->archetypes.size());
    alive = "  uint64_t archetype = (uint64_t)id >> ECS__ROW_BITS;\n"
            "  uint64_t row = (uint64_t)id & ((UINT64_C(1) << ECS__ROW_BITS) "
            "- 1);\n"
            "  return id != ECS_NO_ENTITY && archetype < ECS__ARCHETYPES &&\n"
            "         (int64_t)row < ecs__counts(world)[archetype];\n";
    archetypeOf = "(int32_t)((uint64_t)id >> ECS__ROW_BITS)";
    rowOf = "(int64_t)((uint64_t)id & ((UINT64_C(1) << ECS__ROW_BITS) - 1))";
  } else {
    std::string locationType = uintType(scheme.locationBits);
    os << llvm::formatv("#define ECS__SLOT_BITS {0}\n", scheme.slotBits);
    os << llvm::formatv(
        "#define ECS__NEXT_SLOT ((int64_t *)((char *)world + {0}))\n"
        "#define ECS__LOCATION (({1} *)((char *)world + {2}))\n",
        layout->nextSlotOffset, locationType, layout->locationOffset);
    std::string location = llvm::formatv(
        "  ECS__LOCATION[slot] = ({0})(((uint64_t)archetype << ECS__ROW_BITS) "
        "|\n                             (uint64_t)row);\n",
        locationType);
    std::string inUse = "(int64_t)ecs__slot(id) < *ECS__NEXT_SLOT";
    if (scheme.kind == EntityScheme::Slots) {
      allocate = "  int64_t slot = (*ECS__NEXT_SLOT)++;\n" + location +
                 "  return (ecs_entity)slot;\n";
      alive = "  return id != ECS_NO_ENTITY && " + inUse + ";\n";
    } else {
      os << llvm::formatv(
          "#define ECS__GENERATION_MASK {0}\n"
          "#define ECS__FREE_HEAD ((int64_t *)((char *)world + {1}))\n"
          "#define ECS__GENERATION (({2} *)((char *)world + {3}))\n",
          (uint64_t(1) << scheme.generationBits) - 1, layout->freeHeadOffset,
          uintType(scheme.generationStorageBits), layout->generationOffset);
      allocate = "  int64_t slot;\n"
                 "  if (*ECS__FREE_HEAD != 0) {\n"
                 "    slot = *ECS__FREE_HEAD - 1;\n"
                 "    *ECS__FREE_HEAD = (int64_t)ECS__LOCATION[slot];\n"
                 "  } else {\n"
                 "    slot = (*ECS__NEXT_SLOT)++;\n"
                 "    ECS__GENERATION[slot] = 0;\n"
                 "  }\n" +
                 location +
                 "  return ((ecs_entity)ECS__GENERATION[slot] << "
                 "ECS__SLOT_BITS) |\n         (ecs_entity)slot;\n";
      alive = "  return id != ECS_NO_ENTITY && " + inUse +
              " &&\n         ECS__GENERATION[ecs__slot(id)] ==\n"
              "             (((uint64_t)id >> ECS__SLOT_BITS) & "
              "ECS__GENERATION_MASK);\n";
    }
    os << "static inline uint64_t ecs__slot(ecs_entity id) {\n"
          "  return (uint64_t)id & ((UINT64_C(1) << ECS__SLOT_BITS) - 1);\n"
          "}\n";
    archetypeOf = "(int32_t)(ECS__LOCATION[ecs__slot(id)] >> ECS__ROW_BITS)";
    rowOf = "(int64_t)(ECS__LOCATION[ecs__slot(id)] &\n"
            "                   ((UINT64_C(1) << ECS__ROW_BITS) - 1))";
  }
  os << "static inline ecs_entity ecs__allocate(ecs_world *world, "
        "int32_t archetype,\n"
        "                                       int64_t row) {\n";
  if (scheme.kind == EntityScheme::Rows)
    os << "  (void)world;\n";
  os << allocate << "}\n";
  os << "static inline bool ecs_entity_alive(const ecs_world *world_, "
        "ecs_entity id) {\n"
        "  ecs_world *world = (ecs_world *)world_;\n"
     << alive << "}\n";
  os << "// The archetype (ECS_ARCHETYPE_<name>) and row of a live entity, "
        "or -1.\n"
        "static inline int32_t ecs_entity_archetype(const ecs_world *world_,\n"
        "                                           ecs_entity id) {\n"
        "  ecs_world *world = (ecs_world *)world_;\n"
        "  if (!ecs_entity_alive(world, id))\n    return -1;\n"
        "  return "
     << archetypeOf
     << ";\n}\n"
        "static inline int64_t ecs_entity_row(const ecs_world *world_, "
        "ecs_entity id) {\n"
        "  ecs_world *world = (ecs_world *)world_;\n"
        "  if (!ecs_entity_alive(world, id))\n    return -1;\n"
        "  return "
     << rowOf << ";\n}\n";

  for (const WorldArchetype &archetype : layout->archetypes) {
    ArchetypeOp archetypeOp = archetype.op;
    std::string name = toIdentifier(archetypeOp.getSymName());
    if (failed(claim(archetypeOp, name)))
      return failure();
    os << llvm::formatv("\n// Archetype @{0}\n", archetypeOp.getSymName());
    os << llvm::formatv("#define ECS_{0}_CAPACITY {1}\n", name,
                        archetype.capacity);
    os << llvm::formatv(
        "static inline int64_t ecs_{0}_count(const ecs_world *world) {{\n"
        "  return ((const int64_t *)world)[{1}];\n}\n",
        name, archetype.index);
    os << llvm::formatv("#define ECS_ARCHETYPE_{0} {1}\n", name,
                        archetype.index);
    // Spawn one entity: the next row, a new id, optional components absent.
    // The same steps as ecs.spawn in the lowered program.
    // A new entity starts without its optional components; for reactive
    // queries it has added and changed every other component (stamped with
    // the current tick, one past the counter) and lost none.
    std::string clearPresence;
    for (const WorldColumn &column : archetype.columns) {
      if (column.isPresence()) {
        clearPresence +=
            llvm::formatv("  ((uint8_t *)((char *)world + {0}))[n] = 0;\n",
                          column.offset);
      } else if (column.isStamp()) {
        bool happened =
            column.stamp->kind != Trigger::Removed &&
            !archetypeOp.isOptional(
                FlatSymbolRefAttr::get(column.stamp->component));
        clearPresence += llvm::formatv(
            "  ((int64_t *)((char *)world + {0}))[n] = {1};\n", column.offset,
            happened ? llvm::formatv("*(int64_t *)((char *)world + {0}) + 1",
                                     layout->tickOffset)
                           .str()
                     : std::string("0"));
      }
    }
    os << "// Returns the new entity's id, or ECS_NO_ENTITY if the archetype "
          "is full.\n// Its fields are uninitialised; fill them at "
          "ecs_entity_row(world, id).\n";
    std::string storeId =
        scheme.hasIds()
            ? llvm::formatv("  ((ecs_entity *)((char *)world + {0}))[n] = "
                            "id;\n",
                            archetype.idOffset)
                  .str()
            : std::string();
    os << llvm::formatv(
        "static inline ecs_entity ecs_{0}_spawn(ecs_world *world) {{\n"
        "  int64_t n = ((int64_t *)world)[{1}];\n"
        "  if (n >= ECS_{0}_CAPACITY)\n    return ECS_NO_ENTITY;\n"
        "{2}"
        "  ecs_entity id = ecs__allocate(world, {1}, n);\n"
        "{3}"
        "  ((int64_t *)world)[{1}] = n + 1;\n"
        "  return id;\n}\n",
        name, archetype.index, clearPresence, storeId);
    os << llvm::formatv(
        "// Spawns n entities in consecutive rows; false (and none spawned) "
        "if they\n// do not fit.\n"
        "static inline bool ecs_{0}_spawn_n(ecs_world *world, int64_t n) {{\n"
        "  if (n < 0 || ecs_{0}_count(world) + n > ECS_{0}_CAPACITY)\n"
        "    return false;\n"
        "  for (int64_t i = 0; i < n; ++i)\n"
        "    ecs_{0}_spawn(world);\n"
        "  return true;\n}\n",
        name);
    if (scheme.hasIds()) {
      os << llvm::formatv(
          "// The id of the entity in each row.\n"
          "static inline ecs_entity *ecs_{0}_id(ecs_world *world) {{\n"
          "  return (ecs_entity *)((char *)world + {1});\n}\n",
          name, archetype.idOffset);
      if (failed(claim(archetypeOp, "ecs_" + name + "_id")))
        return failure();
    }
    for (const WorldColumn &column : archetype.columns) {
      // Stamps are the compiler's bookkeeping for reactive queries.
      if (column.isStamp())
        continue;
      bool isPresence = column.isPresence();
      std::string accessor = llvm::formatv(
          "ecs_{0}_{1}_{2}", name, toIdentifier(column.component.getValue()),
          isPresence ? std::string("present")
                     : toIdentifier(column.field.getValue()));
      if (failed(claim(archetypeOp, accessor)))
        return failure();
      StringRef cType = isPresence ? "uint8_t" : getCType(column.type);
      os << llvm::formatv(
          "static inline {0} *{1}(ecs_world *world) {{\n"
          "  return ({0} *)((char *)world + {2});\n}\n",
          cType, accessor, column.offset);
    }
  }

  for (const WorldResource &resource : layout->resources) {
    ResourceOp resourceOp = resource.op;
    std::string name = toIdentifier(resourceOp.getSymName());
    os << llvm::formatv("\n// Resource @{0}\n", resourceOp.getSymName());
    for (const WorldResourceField &field : resource.fields) {
      std::string accessor = llvm::formatv(
          "ecs_{0}_{1}", name, toIdentifier(field.field.getValue()));
      if (failed(claim(resourceOp, accessor)))
        return failure();
      os << llvm::formatv(
          "static inline {0} *{1}(ecs_world *world) {{\n"
          "  return ({0} *)((char *)world + {2});\n}\n",
          getCType(field.type), accessor, field.offset);
    }
  }

  os << "\n// Schedules. The lowered function receives the arena as a "
        "memref descriptor.\n"
        "typedef struct {\n  char *allocated;\n  char *aligned;\n"
        "  int64_t offset;\n  int64_t size;\n  int64_t stride;\n"
        "} ecs_arena_descriptor;\n";
  for (ScheduleOp schedule : module.getOps<ScheduleOp>()) {
    std::string name = toIdentifier(schedule.getSymName());
    if (failed(claim(schedule, name)))
      return failure();
    SmallVector<std::string> params, args;
    for (BlockArgument arg : schedule.getBody().getArguments()) {
      StringRef cType = getCType(arg.getType());
      if (cType.empty())
        return schedule.emitError("parameter #")
               << arg.getArgNumber() << " has type " << arg.getType()
               << ", which has no C equivalent here";
      params.push_back(llvm::formatv("{0} arg{1}", cType, arg.getArgNumber()));
      args.push_back(llvm::formatv("arg{0}", arg.getArgNumber()));
    }
    std::string declParams, callArgs;
    for (auto [param, arg] : llvm::zip(params, args)) {
      declParams += param + ", ";
      callArgs += arg + ", ";
    }
    os << llvm::formatv("\nvoid _mlir_ciface_{0}({1}ecs_arena_descriptor "
                        "*world);\n",
                        schedule.getSymName(), declParams);
    os << llvm::formatv(
        "static inline void ecs_{0}(ecs_world *world{1}{2}) {{\n"
        "  ecs_arena_descriptor arena = {{(char *)world, (char *)world, 0,\n"
        "                                 ECS_WORLD_BYTES, 1};\n"
        "  _mlir_ciface_{3}({4}&arena);\n}\n",
        name, params.empty() ? "" : ", ", llvm::join(params, ", "),
        schedule.getSymName(), callArgs);
  }

  os << "\n#endif // ECS_GENERATED_WORLD_H\n";
  return success();
}

int main(int argc, char **argv) {
  TranslateFromMLIRRegistration header(
      "ecs-to-c-header", "Emit the C API of an ECS program's world",
      [](Operation *op, raw_ostream &os) -> LogicalResult {
        auto module = dyn_cast<ModuleOp>(op);
        if (!module)
          return op->emitError("expected a module");
        return emitHeader(module, os);
      },
      [](DialectRegistry &registry) {
        registry.insert<EcsDialect, arith::ArithDialect, func::FuncDialect,
                        scf::SCFDialect>();
      });
  return failed(mlirTranslateMain(argc, argv, "ECS translation tool"));
}
